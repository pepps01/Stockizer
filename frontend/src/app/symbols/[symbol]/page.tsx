"use client";

import Link from "next/link";
import { use, useEffect, useState } from "react";
import { api } from "@/lib/api";
import { useAuth } from "@/lib/auth-context";
import { useAsync } from "@/lib/use-async";
import { useLiveQuotes } from "@/lib/realtime";
import { currencyLabel, formatCompact, formatNumber, formatPercent, changeClass } from "@/lib/format";
import type { UserActionType } from "@/lib/types";
import { PriceChart, type ChartStyle } from "@/components/charts/PriceChart";
import { SignalCard } from "@/components/symbol/SignalCard";
import { TechnicalsCard } from "@/components/symbol/TechnicalsCard";
import { Flag } from "@/components/ui/Flag";
import { MarketStatus, SourceBadge } from "@/components/ui/Badges";
import { Card, Change, ErrorNote, PageShell, Segmented, Skeleton, Stat } from "@/components/ui/primitives";

const RANGES = ["1M", "3M", "6M", "YTD", "1Y", "5Y"] as const;

export default function SymbolPage({ params }: { params: Promise<{ symbol: string }> }) {
  const symbol = decodeURIComponent(use(params).symbol);
  const [range, setRange] = useState<(typeof RANGES)[number]>("1Y");
  const [style, setStyle] = useState<ChartStyle>("candles");
  const detail = useAsync(() => api.symbol(symbol), [symbol]);
  const history = useAsync(() => api.history(symbol, range), [symbol, range]);
  const live = useLiveQuotes([symbol]);

  const d = detail.data;
  const quote = live[symbol.toUpperCase()] ?? d?.quote;
  const unit = d?.ticker.kind === "index" ? "" : currencyLabel(d?.ticker.currency);

  return (
    <PageShell>
      <ErrorNote message={detail.error} />
      {!d ? (
        <Skeleton className="h-24 w-full" />
      ) : (
        <header className="flex flex-wrap items-start justify-between gap-6">
          <div className="flex items-start gap-4">
            <Flag code={d.ticker.country_code} size={48} />
            <div>
              <div className="flex flex-wrap items-center gap-2 text-sm text-muted-foreground">
                <span className="rounded bg-surface-muted px-2 py-0.5 font-semibold text-foreground">{d.ticker.display_symbol}</span>
                <Link href={`/markets/${d.exchange.code}`} className="hover:text-brand">
                  {d.exchange.name}
                </Link>
                {d.ticker.sector && <span>· {d.ticker.sector}</span>}
                <SourceBadge source={d.ticker.data_source} />
              </div>
              <h1 className="mt-1 text-2xl font-semibold sm:text-3xl">{d.ticker.name}</h1>
              <div className="mt-2 flex flex-wrap items-baseline gap-3">
                <span className="tabular text-3xl font-semibold">{formatNumber(quote?.price)}</span>
                <span className="text-sm text-muted-foreground">{unit}</span>
                <Change value={quote?.change ?? null} percent={quote?.change_percent ?? null} className="text-lg font-medium" />
              </div>
              <div className="mt-1 flex flex-wrap items-center gap-3">
                <MarketStatus open={Boolean(quote?.market_open)} localTime={d.exchange.local_time} />
                <span className="text-xs text-muted-foreground">
                  As of {quote?.as_of}
                  {d.ticker.data_source === "yahoo" ? " · Yahoo Finance (may be delayed)" : " · simulated feed"}
                </span>
              </div>
            </div>
          </div>
          <SymbolActions symbol={d.ticker.symbol} />
        </header>
      )}

      {d?.ticker.data_source === "synthetic" && (
        <p className="mt-4 rounded-xl bg-hold-soft px-4 py-3 text-sm text-hold">
          No free live data feed covers {d.exchange.name}, so this price series is generated by a deterministic model for demonstration. Don&apos;t trade on it.
        </p>
      )}

      <div className="mt-6 grid gap-6 lg:grid-cols-[1fr_22rem]">
        <div className="space-y-6">
          <Card
            title={
              <Segmented
                value={range}
                onChange={setRange}
                options={RANGES.map((r) => ({ value: r, label: r }))}
              />
            }
            action={
              <Segmented
                value={style}
                onChange={setStyle}
                options={[
                  { value: "candles", label: "Candles" },
                  { value: "area", label: "Line" },
                ]}
              />
            }
          >
            {history.data?.bars.length ? <PriceChart bars={history.data.bars} style={style} /> : <Skeleton className="h-[420px]" />}
          </Card>

          {d && (
            <Card title="Key statistics">
              <dl className="grid grid-cols-2 gap-4 text-sm sm:grid-cols-4">
                <Stat label="Open" value={formatNumber(quote?.open)} />
                <Stat label="Day range" value={`${formatNumber(quote?.low)} – ${formatNumber(quote?.high)}`} />
                <Stat label="52-week range" value={`${formatNumber(d.fundamentals.fifty_two_week_low)} – ${formatNumber(d.fundamentals.fifty_two_week_high)}`} />
                <Stat label="Volume" value={formatCompact(quote?.volume)} />
                {d.ticker.kind === "stock" && (
                  <>
                    <Stat label="Market cap" value={`${formatCompact(d.fundamentals.market_cap)} ${unit}`} />
                    <Stat label="P/E (TTM)" value={formatNumber(d.fundamentals.pe_ratio, 2)} />
                    <Stat label="EPS (TTM)" value={formatNumber(d.fundamentals.eps)} />
                    <Stat label="Dividend yield" value={d.fundamentals.dividend_yield != null ? `${d.fundamentals.dividend_yield.toFixed(2)}%` : "—"} />
                    <Stat label="Beta" value={formatNumber(d.fundamentals.beta, 2)} />
                    <Stat label="Avg volume (30D)" value={formatCompact(d.fundamentals.avg_volume_30d)} />
                    <Stat label="Employees" value={formatCompact(d.fundamentals.employees)} />
                    <Stat label="Industry" value={d.fundamentals.industry ?? "—"} />
                  </>
                )}
              </dl>
              <h3 className="mt-6 text-sm font-semibold">Performance</h3>
              <div className="mt-2 grid grid-cols-3 gap-2 sm:grid-cols-6">
                {(["perf_1w", "perf_1m", "perf_3m", "perf_6m", "perf_ytd", "perf_1y"] as const).map((k) => (
                  <div key={k} className="rounded-xl bg-surface-muted p-3 text-center">
                    <div className={`tabular font-semibold ${changeClass(d.performance[k])}`}>{formatPercent(d.performance[k])}</div>
                    <div className="text-[11px] uppercase text-muted-foreground">{k.replace("perf_", "")}</div>
                  </div>
                ))}
              </div>
              {d.fundamentals.description && (
                <>
                  <h3 className="mt-6 text-sm font-semibold">About</h3>
                  <p className="mt-2 text-sm text-muted-foreground">{d.fundamentals.description}</p>
                </>
              )}
            </Card>
          )}
        </div>

        <aside className="space-y-6">
          {d && <SignalCard ticker={d.ticker} />}
          {d && <TechnicalsCard technicals={d.technicals} />}
        </aside>
      </div>
    </PageShell>
  );
}

function SymbolActions({ symbol }: { symbol: string }) {
  const { token } = useAuth();
  const [watching, setWatching] = useState<boolean | null>(null);
  const [note, setNote] = useState<string | null>(null);

  useEffect(() => {
    if (!token) return;
    api.watchlist(token).then(({ items }) => setWatching(items.some((i) => i.symbol === symbol))).catch(() => undefined);
  }, [token, symbol]);

  if (!token) return null;

  const toggle = async () => {
    if (watching) await api.removeFromWatchlist(token, symbol);
    else await api.addToWatchlist(token, symbol);
    setWatching(!watching);
  };
  const journal = async (action: UserActionType) => {
    await api.recordAction(token, symbol, action);
    setNote(`Noted “${action}” in your journal — Algizer never places orders.`);
  };

  return (
    <div className="flex flex-col items-end gap-2">
      <button onClick={toggle} className="btn-secondary">
        {watching ? "★ Watching" : "☆ Add to watchlist"}
      </button>
      <div className="flex gap-1.5" title="Record your own decision (journal only)">
        {(["buy", "hold", "sell"] as const).map((a) => (
          <button key={a} onClick={() => journal(a)} className="rounded-lg border border-border px-3 py-1 text-xs font-medium capitalize hover:bg-surface-muted">
            I {a}
          </button>
        ))}
      </div>
      {note && <p className="max-w-xs text-right text-xs text-muted-foreground">{note}</p>}
    </div>
  );
}
