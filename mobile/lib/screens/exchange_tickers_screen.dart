const _days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

/// One exchange: trading session, indices, listed stocks and movers — plus
/// the hand-off into the Selector (frontend /markets/[exchange]).
class ExchangeScreen extends StatefulWidget {
  const ExchangeScreen({super.key, required this.code});

  final String code;

  @override
  State<ExchangeScreen> createState() => _ExchangeScreenState();
}

class _ExchangeScreenState extends State<ExchangeScreen> {
  late Future<ExchangeListing> _listing;
  late Future<Movers> _movers;
  String _filter = '';

  @override
  void initState() {
    super.initState();
    _load();
  }

  void _load() {
    final api = context.read<ApiClient>();
    _listing = api.exchange(widget.code);
    _movers = api.movers(exchange: widget.code, limit: 4);
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text(widget.code), actions: [IconButton(onPressed: () => openSearch(context), icon: const Icon(Icons.search))]),
      body: RefreshIndicator(
        onRefresh: () async {
          setState(_load);
          await _listing.then<void>((_) {}, onError: (_) {});
        },
        child: FutureBuilder<ExchangeListing>(
          future: _listing,
          builder: (context, snapshot) {
            if (snapshot.hasError) {
              return ListView(padding: const EdgeInsets.all(16), children: [ErrorNote(errorMessage(snapshot.error), onRetry: () => setState(_load))]);
            }
            final listing = snapshot.data;
            if (listing == null) {
              return ListView(padding: const EdgeInsets.all(16), children: const [Skeleton(height: 120), SizedBox(height: 16), SkeletonList(count: 8)]);
            }
            final q = _filter.toLowerCase();
            final stocks = listing.stocks
                .where((r) => q.isEmpty || '${r.info.displaySymbol} ${r.info.name} ${r.info.sector ?? ''}'.toLowerCase().contains(q))
                .toList();
            return ListView(
              padding: const EdgeInsets.fromLTRB(20, 4, 20, 32),
              children: [
                _ExchangeHeader(exchange: listing.exchange),
                if (isSimulated(listing.exchange.dataSource)) ...[
                  const SizedBox(height: 12),
                  Notice(
                    'No free live data feed covers ${listing.exchange.name}, so prices here are generated by a deterministic model for demonstration. Don’t trade on them.',
                    tone: NoticeTone.hold,
                    icon: Icons.science_outlined,
                  ),
                ],
                if (listing.indices.isNotEmpty) ...[
                  const SectionHeader('Indices'),
                  SectionCard(child: MarketList(rows: listing.indices, showCountry: false, showViewSwitch: false)),
                ],
                SectionHeader('Listed stocks', subtitle: '${listing.stocks.length} tickers'),
                TextField(
                  decoration: const InputDecoration(prefixIcon: Icon(Icons.filter_list), hintText: 'Filter by symbol, name or sector'),
                  onChanged: (v) => setState(() => _filter = v),
                ),
                const SizedBox(height: 10),
                SectionCard(
                  child: stocks.isEmpty
                      ? const EmptyState(title: 'No matching stocks', icon: Icons.search_off)
                      : MarketList(rows: stocks, showCountry: false),
                ),
                const SectionHeader('Movers'),
                AsyncView<Movers>(future: _movers, builder: (context, movers) => MoversBoard(movers: movers)),
              ],
            );
          },
        ),
      ),
    );
  }
}

class _ExchangeHeader extends StatelessWidget {
  const _ExchangeHeader({required this.exchange});

  final Exchange exchange;

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    final e = exchange;
    final localClock = e.localTime.length > 11 ? e.localTime.substring(11, e.localTime.length.clamp(11, 16)) : e.localTime;
    final detail = TextStyle(fontSize: 12.5, color: p.mutedForeground);
    return SectionCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Flag(code: e.countryCode, size: 48),
              const SizedBox(width: 12),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(e.name, style: const TextStyle(fontSize: 18, fontWeight: FontWeight.w700)),
                    const SizedBox(height: 2),
                    InkWell(
                      onTap: () => openCountry(context, e.countryCode),
                      child: Text('${e.country} →', style: TextStyle(color: p.brand, fontSize: 13)),
                    ),
                  ],
                ),
              ),
              SourceBadge(source: e.dataSource),
            ],
          ),
          const SizedBox(height: 12),
          Wrap(
            spacing: 14,
            runSpacing: 6,
            crossAxisAlignment: WrapCrossAlignment.center,
            children: [
              MarketStatus(open: e.isOpen),
              Text(e.tradingDays.map((d) => d >= 0 && d < 7 ? _days[d] : '?').join(' · '), style: detail),
              Text('${e.opensAt}–${e.closesAt} (${e.timezone})', style: detail),
              Text('Local time $localClock', style: detail),
              Text('Quoted in ${currencyLabel(e.currency)}', style: detail),
            ],
          ),
          const SizedBox(height: 14),
          FilledButton.icon(
            onPressed: () => openStrategy(context, StrategyIntent.selector(exchange: e.code)),
            icon: const Icon(Icons.filter_alt_outlined, size: 18),
            label: const Text('Rank this exchange with the Selector'),
          ),
        ],
      ),
    );
  }
}
