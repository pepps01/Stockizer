/// Semicircle needle gauge from Strong sell (−1) to Strong buy (+1).
class _GaugePainter extends CustomPainter {
  _GaugePainter({required this.value, required this.palette});

  final double value;
  final AppPalette palette;

  @override
  void paint(Canvas canvas, Size size) {
    final center = Offset(size.width / 2, size.height - 8);
    final radius = math.min(size.width / 2, size.height) - 10;
    final rect = Rect.fromCircle(center: center, radius: radius);
    final arc = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 12
      ..strokeCap = StrokeCap.round
      ..shader = SweepGradient(
        startAngle: math.pi,
        endAngle: 2 * math.pi,
        colors: [palette.loss, palette.mutedForeground, palette.gain],
      ).createShader(rect);
    canvas.drawArc(rect, math.pi, math.pi, false, arc);

    final angle = math.pi * (1 - (value.clamp(-1.0, 1.0) + 1) / 2);
    final tip = center + Offset(math.cos(angle), -math.sin(angle)) * (radius - 8);
    final needle = Paint()
      ..color = palette.foreground
      ..strokeWidth = 3
      ..strokeCap = StrokeCap.round;
    canvas.drawLine(center, tip, needle);
    canvas.drawCircle(center, 5, Paint()..color = palette.foreground);
  }

  @override
  bool shouldRepaint(covariant _GaugePainter old) => old.value != value || old.palette != palette;
}

/// "Stocks · N" | "Chart & signal" on index pages, stocks first (as on the web).
class _IndexTabs extends StatelessWidget {
  const _IndexTabs({required this.index, required this.count, required this.onChanged});

  final int index;
  final int? count;
  final ValueChanged<int> onChanged;

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    Widget tab(int i, String label, int? badge) {
      final active = i == index;
      return Expanded(
        child: InkWell(
          onTap: () {
            if (!active) Haptics.tick();
            onChanged(i);
          },
          child: Container(
            padding: const EdgeInsets.symmetric(vertical: 12),
            decoration: BoxDecoration(border: Border(bottom: BorderSide(color: active ? p.foreground : p.border, width: active ? 2 : 1))),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                Text(label, style: TextStyle(fontSize: 15, fontWeight: FontWeight.w700, color: active ? p.foreground : p.mutedForeground)),
                if (badge != null) ...[
                  const SizedBox(width: 6),
                  Container(
                    padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 1),
                    decoration: BoxDecoration(color: active ? p.ink : p.surfaceMuted, borderRadius: BorderRadius.circular(99)),
                    child: Text('$badge', style: TextStyle(fontSize: 12, fontWeight: FontWeight.w700, color: active ? p.inkForeground : p.mutedForeground)),
                  ),
                ],
              ],
            ),
          ),
        ),
      );
    }

    return Semantics(
      container: true,
      label: 'Index views',
      child: Row(children: [tab(0, 'Stocks', count), tab(1, 'Chart & signal', null)]),
    );
  }
}
