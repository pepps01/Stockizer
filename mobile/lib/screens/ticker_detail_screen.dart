/// Sticky call to action: start the Adviser on this symbol. The interval is
/// picked in a bottom sheet so the page itself stays quiet.
class _MonitorBar extends StatefulWidget {
  const _MonitorBar({required this.symbol, required this.signal});

  final String symbol;
  final Future<(AdviserSignal, String?)> signal;

  @override
  State<_MonitorBar> createState() => _MonitorBarState();
}

class _MonitorBarState extends State<_MonitorBar> {
  int _interval = 300;
  bool _starting = false;

  Future<void> _pickAndStart() async {
    final p = context.palette;
    final picked = await showModalBottomSheet<int>(
      context: context,
      showDragHandle: true,
      backgroundColor: p.surface,
      builder: (context) => SafeArea(
        child: Padding(
          padding: const EdgeInsets.fromLTRB(20, 0, 20, 16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              Text('Monitor ${widget.symbol}', style: const TextStyle(fontSize: 20, fontWeight: FontWeight.w700)),
              const SizedBox(height: 4),
              Text(
                'How often should the Adviser re-evaluate it? You’ll get a notification whenever the signal changes.',
                style: TextStyle(fontSize: 13, height: 1.45, color: p.mutedForeground),
              ),
              const SizedBox(height: 12),
              for (final (value, label) in monitorIntervals)
                Container(
                  decoration: BoxDecoration(border: Border(bottom: BorderSide(color: p.border))),
                  child: ListTile(
                    contentPadding: EdgeInsets.zero,
                    title: Text(label, style: const TextStyle(fontSize: 15)),
                    trailing: value == _interval ? Icon(Icons.check, color: p.foreground, size: 20) : null,
                    onTap: () => Navigator.pop(context, value),
                  ),
                ),
            ],
          ),
        ),
      ),
    );
    if (picked == null || !mounted) return;
    setState(() => _interval = picked);
    await _start();
  }

  Future<void> _start() async {
    final token = context.read<AuthProvider>().token;
    if (token == null) return;
    setState(() => _starting = true);
    try {
      final (_, runId) = await widget.signal.then<(AdviserSignal?, String?)>((v) => v, onError: (_) => (null, null));
      if (!mounted) return;
      await context.read<ApiClient>().createSession(token, symbol: widget.symbol, intervalSec: _interval, optimizerRunId: runId);
      if (!mounted) return;
      Haptics.alert();
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: const Text('Monitoring started. New signals arrive as notifications.'),
          action: SnackBarAction(label: 'Adviser', onPressed: () => openStrategy(context, const StrategyIntent.adviser())),
        ),
      );
    } catch (e) {
      if (mounted) showSnack(context, errorMessage(e), error: true);
    } finally {
      if (mounted) setState(() => _starting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    if (context.watch<AuthProvider>().token == null) return const SizedBox.shrink();
    return Container(
      decoration: BoxDecoration(color: p.surface, border: Border(top: BorderSide(color: p.border))),
      child: SafeArea(
        top: false,
        child: Padding(
          padding: const EdgeInsets.fromLTRB(20, 12, 20, 12),
          child: BusyButton(
            label: 'Monitor with Adviser',
            busyLabel: 'Starting…',
            icon: Icons.notifications_active_outlined,
            busy: _starting,
            onPressed: _pickAndStart,
          ),
        ),
      ),
    );
  }
}

/// Score S ∈ [−1, 1] on a quiet track. The ±θ HOLD band is shaded; the marker
/// takes the colour of the decision it falls into.
class ScoreBar extends StatelessWidget {
  const ScoreBar({super.key, required this.score, required this.threshold, this.color});

  final double score;
  final double threshold;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    double pos(double v) => ((v.clamp(-1.0, 1.0) + 1) / 2);
    final label = TextStyle(fontSize: 10.5, fontWeight: FontWeight.w700, letterSpacing: 1, color: p.mutedForeground);
    return Column(
      children: [
        LayoutBuilder(
          builder: (context, constraints) {
            final w = constraints.maxWidth;
            return SizedBox(
              height: 20,
              child: Stack(
                clipBehavior: Clip.none,
                alignment: Alignment.centerLeft,
                children: [
                  Container(
                    height: 6,
                    decoration: BoxDecoration(color: p.surfaceMuted, borderRadius: BorderRadius.circular(99)),
                  ),
                  Positioned(
                    left: w * pos(-threshold),
                    width: w * (pos(threshold) - pos(-threshold)),
                    top: 7,
                    height: 6,
                    child: Container(color: p.holdSoft),
                  ),
                  Positioned(
                    left: w / 2 - 0.5,
                    top: 4,
                    child: Container(width: 1, height: 12, color: p.border),
                  ),
                  Positioned(
                    left: (w * pos(score) - 10).clamp(0.0, w - 20),
                    child: Container(
                      width: 20,
                      height: 20,
                      decoration: BoxDecoration(
                        color: p.surface,
                        shape: BoxShape.circle,
                        border: Border.all(color: color ?? p.foreground, width: 5),
                      ),
                    ),
                  ),
                ],
              ),
            );
          },
        ),
        const SizedBox(height: 8),
        Row(
          children: [
            Text('SELL', style: label),
            Expanded(
              child: Text(
                'S ${formatSigned(score, 2)}  ·  θ ±${threshold.toStringAsFixed(2)}',
                textAlign: TextAlign.center,
                style: TextStyle(fontSize: 11.5, color: p.mutedForeground, fontFeatures: priceFeatures),
              ),
            ),
            Text('BUY', style: label),
          ],
        ),
      ],
    );
  }
}

