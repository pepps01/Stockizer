const _ranges = ['1M', '3M', '6M', 'YTD', '1Y', '5Y'];

/// Symbol page (frontend /symbols/[symbol]): live quote, chart, statistics,
/// the Adviser's current signal and the technical rating.
class SymbolScreen extends StatefulWidget {
  const SymbolScreen({super.key, required this.symbol});

  final String symbol;

  @override
  State<SymbolScreen> createState() => _SymbolScreenState();
}

class _SymbolScreenState extends State<SymbolScreen> {
  late Future<SymbolDetail> _detail;
  late Future<List<Bar>> _history;
  late Future<(AdviserSignal, String?)> _signal;
  String _range = '1Y';

  /// Index pages: 0 = Stocks (first, the default), 1 = Chart & signal.
  int _indexTab = 0;

  /// (bar under the finger, first bar of the range) while scrubbing the chart.
  final _scrub = ValueNotifier<(Bar, Bar)?>(null);

  @override
  void dispose() {
    _scrub.dispose();
    super.dispose();
  }

  @override
  void initState() {
    super.initState();
    _load();
  }

  void _load() {
    final api = context.read<ApiClient>();
    _detail = api.symbol(widget.symbol);
    _history = api.history(widget.symbol, _range);
    _signal = api.signal(widget.symbol, token: context.read<AuthProvider>().token);
  }

  int? _membersCount;

  void _setRange(String range) => setState(() {
    _range = range;
    _history = context.read<ApiClient>().history(widget.symbol, range);
  });

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.symbol, style: const TextStyle(fontSize: 15, fontWeight: FontWeight.w700)),
        centerTitle: true,
        actions: [WatchlistButton(symbol: widget.symbol)],
      ),
      bottomNavigationBar: _MonitorBar(symbol: widget.symbol, signal: _signal),
      body: FutureBuilder<SymbolDetail>(
        future: _detail,
        builder: (context, snapshot) {
          if (snapshot.hasError) {
            return ListView(
              padding: const EdgeInsets.all(20),
              children: [ErrorNote(errorMessage(snapshot.error), onRetry: () => setState(_load))],
            );
          }
          final d = snapshot.data;
          if (d == null) {
            return ListView(
              padding: const EdgeInsets.all(20),
              children: const [Skeleton(height: 110), SizedBox(height: 16), Skeleton(height: 280)],
            );
          }
          return RefreshIndicator(
            onRefresh: () async {
              setState(_load);
              await _detail.then<void>((_) {}, onError: (_) {});
            },
            child: LiveQuotes(
              symbols: [d.ticker.symbol],
              builder: (context, live) {
                final quote = live[d.ticker.symbol] ?? d.quote;
                return ListView(
                  padding: const EdgeInsets.fromLTRB(20, 4, 20, 32),
                  children: [
                    _Header(detail: d, quote: quote, scrub: _scrub, range: _range),
                    if (isSimulated(d.ticker.dataSource)) ...[
                      const SizedBox(height: 14),
                      Notice(
                        'No free live data feed covers ${d.exchange.name}, so this price series is generated by a deterministic model for demonstration. Don’t trade on it.',
                        tone: NoticeTone.hold,
                        icon: Icons.science_outlined,
                      ),
                    ],
                    if (d.ticker.isIndex) ...[
                      const SizedBox(height: 18),
                      _IndexTabs(
                        index: _indexTab,
                        count: _membersCount,
                        onChanged: (i) => setState(() => _indexTab = i),
                      ),
                    ],
                    if (d.ticker.isIndex && _indexTab == 0) ...[
                      const SizedBox(height: 16),
                      IndexStocks(
                        symbol: d.ticker.symbol,
                        onCount: (n) {
                          if (mounted && _membersCount != n) setState(() => _membersCount = n);
                        },
                      ),
                    ] else ...[
                    const SizedBox(height: 20),
                    AsyncView<List<Bar>>(
                      future: _history,
                      loading: const Skeleton(height: 240),
                      builder: (context, bars) =>
                          PriceChart(bars: bars, onScrub: (bar) => _scrub.value = bar == null ? null : (bar, bars.first)),
                    ),
                    const SizedBox(height: 12),
                    _RangePills(value: _range, onChanged: _setRange),
                    const SizedBox(height: 24),
                    _SignalSection(ticker: d.ticker, signal: _signal),
                    if (d.ticker.kind == 'stock')
                      SectionCard(
                        title: 'Your decision',
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.stretch,
                          children: [
                            Text(
                              'Assume a call to track it in your Investor profile. Stockiser never places orders.',
                              style: TextStyle(fontSize: 13, color: p.mutedForeground),
                            ),
                            const SizedBox(height: 12),
                            JournalButtons(symbol: d.ticker.symbol),
                          ],
                        ),
                      ),
                    _Statistics(detail: d, quote: quote),
                    TechnicalsCard(technicals: d.technicals),
                    ],
                  ],
                );
              },
            ),
          );
        },
      ),
    );
  }
}

/// Chart ranges as quiet text pills; the selected one is an ink pill.
class _RangePills extends StatelessWidget {
  const _RangePills({required this.value, required this.onChanged});

  final String value;
  final ValueChanged<String> onChanged;

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    return Row(
      mainAxisAlignment: MainAxisAlignment.spaceBetween,
      children: [
        for (final r in _ranges)
          Semantics(
            button: true,
            selected: r == value,
            child: GestureDetector(
              behavior: HitTestBehavior.opaque,
              onTap: () {
                if (r != value) Haptics.tick();
                onChanged(r);
              },
              child: AnimatedContainer(
                duration: const Duration(milliseconds: 160),
                padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
                decoration: BoxDecoration(color: r == value ? p.ink : Colors.transparent, borderRadius: BorderRadius.circular(999)),
                child: Text(
                  r,
                  style: TextStyle(fontSize: 13, fontWeight: FontWeight.w700, color: r == value ? p.inkForeground : p.mutedForeground),
                ),
              ),
            ),
          ),
      ],
    );
  }
}

class _Header extends StatelessWidget {
  const _Header({required this.detail, required this.quote, required this.scrub, required this.range});

  final ValueListenable<(Bar, Bar)?> scrub;
  final String range;

  final SymbolDetail detail;
  final Quote? quote;

  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    final t = detail.ticker;
    final unit = t.isIndex ? '' : currencyLabel(t.currency);
    final meta = TextStyle(fontSize: 13, color: p.mutedForeground);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Flag(code: t.countryCode, size: 18),
            const SizedBox(width: 8),
            Expanded(
              child: Wrap(
                spacing: 6,
                runSpacing: 4,
                crossAxisAlignment: WrapCrossAlignment.center,
                children: [
                  Text(t.displaySymbol, style: meta.copyWith(fontWeight: FontWeight.w700, color: p.foreground)),
                  Text('·', style: meta),
                  InkWell(
                    onTap: () => openExchange(context, detail.exchange.code),
                    child: Text(detail.exchange.name, style: meta.copyWith(decoration: TextDecoration.underline, decorationColor: p.border)),
                  ),
                  if (t.sector != null) Text('· ${t.sector}', style: meta),
                  SourceBadge(source: t.dataSource),
                ],
              ),
            ),
          ],
        ),
        const SizedBox(height: 8),
        Text(t.name, style: const TextStyle(fontSize: 24, fontWeight: FontWeight.w700, height: 1.2)),
        const SizedBox(height: 10),
        // Live quote, or the scrubbed bar while a finger is on the chart.
        ValueListenableBuilder<(Bar, Bar)?>(
          valueListenable: scrub,
          builder: (context, scrubbed, _) {
            final bar = scrubbed?.$1;
            final first = scrubbed?.$2;
            final change = bar == null ? quote?.change : bar.close - first!.close;
            final percent = bar == null ? quote?.changePercent : (first!.close == 0 ? null : change! / first.close * 100);
            const priceStyle = TextStyle(fontSize: 44, fontWeight: FontWeight.w300, height: 1.05, fontFeatures: priceFeatures);
            return Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  crossAxisAlignment: CrossAxisAlignment.baseline,
                  textBaseline: TextBaseline.alphabetic,
                  children: [
                    if (bar == null)
                      TickingPrice(value: quote?.price, style: priceStyle)
                    else
                      Text(formatNumber(bar.close), style: priceStyle),
                    if (unit.isNotEmpty) Text(' $unit', style: TextStyle(fontSize: 14, color: p.mutedForeground)),
                  ],
                ),
                const SizedBox(height: 4),
                ChangeText(percent, change: change, style: const TextStyle(fontSize: 15, fontWeight: FontWeight.w700)),
                const SizedBox(height: 6),
                if (bar != null)
                  Text(
                    '${bar.time.split('T').first} · change since ${first!.time.split('T').first} ($range)',
                    style: TextStyle(fontSize: 12, color: p.mutedForeground),
                  )
                else
                  Wrap(
                    spacing: 12,
                    crossAxisAlignment: WrapCrossAlignment.center,
                    children: [
                      MarketStatus(open: quote?.marketOpen ?? false),
                      Text(
                        'As of ${quote?.asOf ?? '—'}${isSimulated(t.dataSource) ? ' · simulated feed' : ' · Yahoo Finance, may be delayed'}',
                        style: TextStyle(fontSize: 12, color: p.mutedForeground),
                      ),
                    ],
                  ),
              ],
            );
          },
        ),
      ],
    );
  }
}

